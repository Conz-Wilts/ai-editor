// Writes src/registry.generated.ts: the user's own motion-graphics components (<library>/components/<id>/, each a
// component.json and the index.tsx it names), copied into src/user-components/<id>/ so the bundler, tsc and esbuild
// all see them as plain relative imports. render.mjs runs it before every bundle; the built-ins never change here.
//
//   node scripts/gen-registry.mjs [--src <dir>] [--dirs <a>;<b>]   default dirs: AI_EDITOR_COMPONENT_DIRS, else <library>/components
//
// A user component may not reuse a built-in id, and a broken one (no manifest, bad id, missing entry) is left out
// with a line on stderr, so one bad folder never stops a render.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ID_RE = /^[a-z][a-z0-9_-]{1,40}$/;

/** The library folder, as library.py finds it: AI_EDITOR_LIBRARY, then $AI_EDITOR_HOME/library.json, then the default. */
export const libraryDir = () => {
  if (process.env.AI_EDITOR_LIBRARY?.trim()) return process.env.AI_EDITOR_LIBRARY.trim().replace(/^~/, os.homedir());
  const home = process.env.AI_EDITOR_HOME || path.join(os.homedir(), ".ai-video-editor");
  try {
    const p = JSON.parse(fs.readFileSync(path.join(home, "library.json"), "utf8")).path;
    if (p) return p.replace(/^~/, os.homedir());
  } catch { /* none saved */ }
  return path.join(os.homedir(), process.platform === "darwin" ? "Movies" : "Videos", "AI Editor");
};

export const componentDirs = (dirs) => dirs ?? (process.env.AI_EDITOR_COMPONENT_DIRS
  ? process.env.AI_EDITOR_COMPONENT_DIRS.split(path.delimiter).filter(Boolean) : [path.join(libraryDir(), "components")]);

/** The built-in ids, read from the registries themselves so a user id can never shadow one. */
const builtinIds = (src) => {
  const ids = new Set(["caption_page", "logo", "plain"]);
  for (const f of ["Templates.tsx", "Overlays.tsx"]) {
    const text = fs.readFileSync(path.join(src, f), "utf8");
    for (const m of text.matchAll(/export const (?:TEMPLATES|OVERLAYS)[^=]*=\s*\{([^}]*)\}/g))
      for (const k of m[1].matchAll(/([a-z_]+)\s*:/g)) ids.add(k[1]);
  }
  return ids;
};

const copyDir = (from, to) => {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    if (e.name === "node_modules" || e.name.startsWith(".")) continue;
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) copyDir(a, b);
    else if (/\.(tsx?|json|css|svg|png|jpe?g|webp)$/i.test(e.name)) fs.copyFileSync(a, b);
  }
};

export const generate = ({ src = path.join(HERE, "..", "src"), dirs, log = (s) => process.stderr.write(s + "\n") } = {}) => {
  const builtins = builtinIds(src);
  const found = [];
  for (const root of componentDirs(dirs)) {
    if (!fs.existsSync(root)) continue;
    for (const id of fs.readdirSync(root).sort()) {
      const dir = path.join(root, id), mf = path.join(dir, "component.json");
      if (!fs.existsSync(mf)) continue;
      let m;
      try { m = JSON.parse(fs.readFileSync(mf, "utf8")); } catch (e) { log(`components: ${mf} unreadable, skipped`); continue; }
      const entry = String(m.entry ?? "");
      if (m.id !== id || !ID_RE.test(id)) { log(`components: ${dir}: id must be its folder name (${ID_RE}), skipped`); continue; }
      if (builtins.has(id)) { log(`components: ${id} is a built-in name, skipped`); continue; }
      if (found.some((f) => f.id === id)) continue;
      if (!/\.(tsx|ts)$/.test(entry) || !fs.existsSync(path.join(dir, entry))) { log(`components: ${id}: entry ${entry} not found, skipped`); continue; }
      found.push({ id, dir, entry: entry.replace(/^\.\//, "").replace(/\.(tsx|ts)$/, ""), floating: !!m.floating });
    }
  }
  const out = path.join(src, "user-components");
  fs.rmSync(out, { recursive: true, force: true });
  for (const c of found) copyDir(c.dir, path.join(out, c.id));
  const ident = (id) => "C_" + id.replace(/[^a-z0-9]/g, "_");
  const body = [
    "// GENERATED by scripts/gen-registry.mjs from the user's own components (<library>/components/<id>/). Do not edit:",
    "// render.mjs regenerates it before every bundle. Built-ins stay in Templates.tsx and Overlays.tsx.",
    'import type React from "react";',
    'import type { TP } from "./Templates";',
    ...found.map((c) => `import ${ident(c.id)} from "./user-components/${c.id}/${c.entry}";`),
    "",
    `export const USER_COMPONENTS: Record<string, React.FC<TP>> = {${found.map((c) => ` ${JSON.stringify(c.id)}: ${ident(c.id)},`).join("")}${found.length ? " " : ""}};`,
    `export const USER_FLOATING: string[] = ${JSON.stringify(found.filter((c) => c.floating).map((c) => c.id))};`,
    "",
  ].join("\n");
  const file = path.join(src, "registry.generated.ts");
  const had = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (had !== body) fs.writeFileSync(file, body);   // unchanged: the bundler's cache stays warm
  return found.map((c) => c.id);
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const a = process.argv.slice(2);
  const opt = (k) => { const i = a.indexOf(k); return i >= 0 ? a[i + 1] : undefined; };
  const ids = generate({ src: opt("--src"), dirs: opt("--dirs")?.split(";").filter(Boolean) });
  console.log(ids.length ? `components: ${ids.join(", ")}` : "components: none of the user's own");
}
